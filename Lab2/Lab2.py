import numpy as np
import cupy as cp
import pycuda.driver as cuda
import pycuda.autoprimaryctx
from pycuda.compiler import SourceModule
import matplotlib.pyplot as plt
import time

rozmiary = [128, 256, 512, 1024]

czasy_cpu = []
czasy_gpu = []
czasy_kernel = []

kernel_code = """
__global__ void matrixMul(float *A, float *B, float *C, int N) {
    int row = blockIdx.y * blockDim.y + threadIdx.y;
    int col = blockIdx.x * blockDim.x + threadIdx.x;
    float sum = 0.0;

    if (row < N && col < N) {
        for (int k = 0; k < N; k++) {
            sum += A[row * N + k] * B[k * N + col];
        }
        C[row * N + col] = sum;
    }
}
"""

mod = SourceModule(kernel_code)
matrixMul = mod.get_function("matrixMul")

for N in rozmiary:
    A_cpu = np.random.rand(N, N).astype(np.float32)
    B_cpu = np.random.rand(N, N).astype(np.float32)

    # CPU
    start = time.perf_counter()
    C_cpu = np.matmul(A_cpu, B_cpu)
    end = time.perf_counter()

    czasy_cpu.append(end - start)

    # GPU - CuPy
    A_cp = cp.array(A_cpu)
    B_cp = cp.array(B_cpu)

    cp.matmul(A_cp, B_cp)
    cp.cuda.Stream.null.synchronize()

    start = time.perf_counter()
    C_cp = cp.matmul(A_cp, B_cp)
    cp.cuda.Stream.null.synchronize()
    end = time.perf_counter()

    czasy_gpu.append(end - start)

    # GPU - Kernel CUDA
    C_result = np.empty((N, N), dtype=np.float32)

    A_gpu = cuda.mem_alloc(A_cpu.nbytes)
    B_gpu = cuda.mem_alloc(B_cpu.nbytes)
    C_gpu = cuda.mem_alloc(C_result.nbytes)

    cuda.memcpy_htod(A_gpu, A_cpu)
    cuda.memcpy_htod(B_gpu, B_cpu)

    block_size = (32, 32, 1)
    grid_size = ((N + 31) // 32, (N + 31) // 32, 1)

    start = time.perf_counter()

    matrixMul(
        A_gpu, B_gpu, C_gpu, np.int32(N),
        block=block_size,
        grid=grid_size
    )

    cuda.Context.synchronize()
    end = time.perf_counter()

    czasy_kernel.append(end - start)

    cuda.memcpy_dtoh(C_result, C_gpu)

    print(f"Macierz {N}x{N}")
    print(f"CPU: {czasy_cpu[-1]:.5f} s")
    print(f"GPU CuPy: {czasy_gpu[-1]:.5f} s")
    print(f"GPU Kernel: {czasy_kernel[-1]:.5f} s")
    print("Poprawność kernela:",
          np.allclose(C_cpu, C_result, rtol=1e-3, atol=1e-2))
    print()

    del A_gpu, B_gpu, C_gpu

# WYKRES
plt.figure(figsize=(10, 6))

plt.plot(rozmiary, czasy_cpu, marker='o', label='CPU NumPy')
plt.plot(rozmiary, czasy_gpu, marker='o', label='GPU CuPy')
plt.plot(rozmiary, czasy_kernel, marker='o', label='GPU Kernel CUDA')

plt.xlabel("Rozmiar macierzy N x N")
plt.ylabel("Czas wykonania [s]")
plt.title("Porównanie wydajności CPU i GPU")
plt.legend()
plt.grid(True)
plt.show()

